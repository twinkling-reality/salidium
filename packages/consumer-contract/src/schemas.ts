/**
 * Change feed messages, one JSON object per server-sent `data:` line.
 *
 * The feed carries notifications, not state: it says a report changed and how to recognize a newer
 * one, and the consumer fetches the report. Every connection starts with `resync`, which means
 * "discard what you think you know and re-read the list". There is no replay, so after any
 * disconnect the consumer reconnects and receives `resync` again. Unknown message types must be
 * ignored.
 */
const FeedBase = <T extends string>(type: T) => ({
  format: z.literal('salidium.session-feed'),
  version: z.literal(1),
  type: z.literal(type),
  at: Timestamp,
});

export const FeedResyncSchema = z.object({
  ...FeedBase('resync'),
  reason: z.literal('connected'),
});

export const FeedSessionChangedSchema = z.object({
  ...FeedBase('session.changed'),
  sessionId: Text(1100),
  native: NativeIdentitySchema,
  evidenceSeq: Count,
  status: SessionStatusSchema,
  explanation: ExplanationStatusSchema,
});

export const FeedSessionRemovedSchema = z.object({
  ...FeedBase('session.removed'),
  sessionId: Text(1100),
  native: NativeIdentitySchema.nullable(),
});

export const FeedHeartbeatSchema = z.object(FeedBase('heartbeat'));

export const FeedClosingSchema = z.object({
  ...FeedBase('closing'),
  reason: z.enum(['credential-revoked', 'shutting-down']),
});

export const FeedMessageSchema = z.discriminatedUnion('type', [
  FeedResyncSchema,
  FeedSessionChangedSchema,
  FeedSessionRemovedSchema,
  FeedHeartbeatSchema,
  FeedClosingSchema,
]);
export type FeedMessage = z.infer<typeof FeedMessageSchema>;
